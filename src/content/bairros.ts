export interface Bairro {
  slug: string
  nome: string
  /** Nome curto para o <title>, quando o completo estoura os 60 chars do Google. */
  nomeSeo?: string
  /** slug da região urbana (ver `regioes.ts`) */
  regiao: string
  tier: 1 | 2 | 3
  /** false = área conhecida por busca, mas não é bairro na divisão oficial */
  oficialPlanurb: boolean
  /** Perfil de imóvel predominante — orienta o serviço em destaque na landing. */
  perfil: string
  aliases: string[]
  pontosReferencia: string[]
  /**
   * Contexto hiperlocal: como o perfil de imóvel do bairro muda a EXECUÇÃO da
   * obra. É o conteúdo único que impede thin content na página do bairro.
   *
   * Escrever só o que é verificável ou o que decorre do perfil do bairro.
   * Nunca inventar condomínio, rua ou obra realizada (ver .claude/rules/conteudo.md).
   */
  contexto?: string[]
  /**
   * true = a copy hiperlocal já foi escrita e revisada. O gate
   * `check:thin-content` só cobra as páginas marcadas como revisadas, e reporta
   * quantas ainda faltam. Bairro novo nasce false.
   */
  copyRevisada: boolean
}


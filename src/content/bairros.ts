/** Bairros que NÃO entram na base, por decisão do dono. Documentado para não voltarem. */
export const BAIRROS_EXCLUIDOS = ['Los Angeles', 'Aquários'] as const

export function getBairro(slug: string): Bairro | undefined {
  return BAIRROS.find((b) => b.slug === slug)
}

export function getBairrosPorRegiao(regiaoSlug: string): Bairro[] {
  return BAIRROS.filter((b) => b.regiao === regiaoSlug).sort((a, b) =>
    a.nome.localeCompare(b.nome, 'pt-BR')
  )
}

export function getBairrosPorTier(tier: 1 | 2 | 3): Bairro[] {
  return BAIRROS.filter((b) => b.tier === tier)
}

/** Bairros prioritários para a Nobre Cor (alto padrão). */
export const BAIRROS_PRIORITARIOS = BAIRROS.filter((b) => b.tier === 1)

/** Agrupamento pronto para a página /bairros, na ordem das regiões urbanas. */
export function getBairrosAgrupados() {
  return REGIOES_URBANAS.map((regiao) => ({
    regiao,
    bairros: getBairrosPorRegiao(regiao.slug),
  }))
}

